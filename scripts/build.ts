// Build script. B0 provides the development run; B8 adds compiling and packaging.
//   bun run dev     start the server from source (TECH-SPEC 4.7)
//   bun run build   compile dist/lockin-linux-x64 with every served file embedded (TECH-SPEC 4.6)
//   bun run build -- --baseline   the same for CPUs without AVX2: dist/lockin-linux-x64-baseline

import { existsSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { join, relative, resolve } from "node:path";

export const ROOT = resolve(import.meta.dir, "..");
export const TARGET = "bun-linux-x64";
export const OUTFILE = "dist/lockin-linux-x64";
/** For CPUs without AVX2 (REVIEW finding 11); the release workflow builds both (SA-16). */
export const BASELINE_TARGET = "bun-linux-x64-baseline";
export const BASELINE_OUTFILE = "dist/lockin-linux-x64-baseline";
const EMBEDDED_TS = "src/server/embedded.ts";

/**
 * What the binary carries, as repo-relative paths (the keys the server's
 * FileSource reads, see src/server/static.ts): everything in public/
 * (including the vendored Arrow), the copy pools, the default theme's tokens,
 * the bundled fonts with their licences, and the Lock-In logo.
 */
export const EMBED_ROOTS = ["public", "docs/brand/copy.en.json", "docs/design/tokens.css", "docs/design/fonts", "docs/design/logo"];

/** Every file to embed, sorted, skipping hidden files and folders. */
export function embeddedPaths(root: string = ROOT): string[] {
  const out: string[] = [];
  const walk = (abs: string) => {
    const name = abs.split("/").pop()!;
    if (name.startsWith(".")) return;
    if (statSync(abs).isDirectory()) {
      for (const child of readdirSync(abs)) walk(join(abs, child));
    } else {
      out.push(relative(root, abs).split("\\").join("/"));
    }
  };
  for (const entry of EMBED_ROOTS) {
    const abs = join(root, entry);
    if (!existsSync(abs)) throw new Error(`Cannot embed ${entry}: it does not exist.`);
    walk(abs);
  }
  return out.sort();
}

/**
 * The generated entry point of the binary: imports every file with
 * `{ type: "file" }` so `bun build --compile` embeds it, maps repo paths to
 * the embedded copies, and runs main() with that FileSource.
 */
export function embeddedModule(paths: string[]): string {
  const imports = paths.map((p, i) => `import f${i} from ${JSON.stringify(`../../${p}`)} with { type: "file" };`).join("\n");
  const entries = paths.map((p, i) => `  [${JSON.stringify(p)}, f${i}],`).join("\n");
  return `// GENERATED by scripts/build.ts for \`bun run build\`; deleted after the build. Do not edit or commit.
// The compiled binary's entry point: serves files embedded in it (TECH-SPEC 4.6).

import type { FileSource } from "./static.ts";
import { main } from "./main.ts";
${imports}

const FILES = new Map<string, string>([
${entries}
]);

export const embeddedSource: FileSource = {
  async read(path) {
    const at = FILES.get(path);
    return at ? new Uint8Array(await Bun.file(at).arrayBuffer()) : null;
  },
  exists(path) {
    return FILES.has(path);
  },
};

const code = await main(process.argv.slice(2), process.env, process.cwd(), { files: embeddedSource });
if (code >= 0) process.exit(code);
`;
}

/** Compiles the binary. Returns its absolute path. */
export async function compile(opts: { root?: string; outfile?: string; quiet?: boolean; target?: string } = {}): Promise<string> {
  const root = opts.root ?? ROOT;
  const outfile = resolve(root, opts.outfile ?? OUTFILE);
  const paths = embeddedPaths(root);
  const entry = join(root, EMBEDDED_TS);
  writeFileSync(entry, embeddedModule(paths));
  try {
    const proc = Bun.spawn(["bun", "build", "--compile", `--target=${opts.target ?? TARGET}`, entry, "--outfile", outfile], {
      cwd: root,
      stdout: opts.quiet ? "pipe" : "inherit",
      stderr: opts.quiet ? "pipe" : "inherit",
    });
    const code = await proc.exited;
    if (code !== 0) {
      const err = opts.quiet ? await new Response(proc.stderr).text() : "";
      throw new Error(`bun build --compile failed (exit ${code}). ${err}`);
    }
  } finally {
    rmSync(entry, { force: true });
  }
  if (!opts.quiet) console.log(`Built ${relative(root, outfile)} with ${paths.length} embedded files.`);
  return outfile;
}

if (import.meta.main) {
  const [command = "dev", ...rest] = process.argv.slice(2);

  if (command === "dev") {
    const args = ["--watch", "src/server/main.ts", "serve"];
    // Development defaults (TECH-SPEC 4.7), overridable by flags passed after `bun run dev --`.
    if (!rest.some((a) => a.startsWith("--public-url"))) args.push("--public-url", "http://localhost:8080");
    if (!rest.some((a) => a.startsWith("--bind"))) args.push("--bind", "127.0.0.1");
    if (!rest.some((a) => a.startsWith("--data"))) args.push("--data", "./lockin-data");
    const proc = Bun.spawn(["bun", ...args, ...rest], { stdio: ["inherit", "inherit", "inherit"] });
    process.on("SIGINT", () => proc.kill("SIGINT"));
    process.on("SIGTERM", () => proc.kill("SIGTERM"));
    process.exit(await proc.exited);
  } else if (command === "compile") {
    await compile(rest.includes("--baseline") ? { target: BASELINE_TARGET, outfile: BASELINE_OUTFILE } : {});
  } else {
    console.error(`Unknown build command "${command}". Use "dev" or "compile".`);
    process.exit(2);
  }
}
