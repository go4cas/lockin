// Writes the sample venue themes used by the wireframes, through the same
// derivation the server uses (derive.ts). Run: bun docs/design/tools/sample-themes.ts
import { deriveBrandTokens, checkReadability, type BrandInputs } from "./derive.ts";
import { writeFileSync } from "node:fs";
import { join } from "node:path";

const samples: { file: string; venue: string; inputs: BrandInputs; display: string }[] = [
  {
    file: "brass-and-oak",
    venue: "The Example Arms",
    inputs: { background: "#1c140f", text: "#f3e6cc", accent: "#d9a441", accent2: "#8cc2a8" },
    display: '"Alfa Slab One"',
  },
  {
    file: "neon-taproom",
    venue: "Neon Taproom",
    inputs: { background: "#0e0b1a", text: "#f2f0ff", accent: "#ff3ea5", accent2: "#2ef2e2" },
    display: '"Bebas Neue"',
  },
  {
    // Deliberately poor: shows the branding screen's warnings.
    file: "too-light",
    venue: "Daylight Bar",
    inputs: { background: "#f4efe4", text: "#5c5c5c", accent: "#ffd54f", accent2: "#9ad0c2" },
    display: '"Caveat Brush"',
  },
];

for (const s of samples) {
  const t = deriveBrandTokens(s.inputs);
  const lines = Object.entries(t).map(([k, v]) => `  --${k}: ${v};`);
  lines.push(`  --brand-font-display: ${s.display}, "Atkinson Hyperlegible", "Segoe UI", Roboto, Helvetica, Arial, sans-serif;`);
  lines.push(`  --wf-venue: "${s.venue}"; /* wireframe only */`);
  const checks = checkReadability(s.inputs).filter((c) => c.level !== "ok");
  const head = `/* Sample venue theme "${s.venue}" (fictional). Generated by docs/design/tools/sample-themes.ts.\n   Readability: ${checks.length ? checks.map((c) => `${c.pair} ${c.level} (${c.ratio})`).join("; ") : "all checks ok"} */\n`;
  writeFileSync(join(import.meta.dir, "..", "wireframes", "themes", `${s.file}.css`), head + ":root {\n" + lines.join("\n") + "\n}\n");
  console.log(s.file, checks.map((c) => `${c.pair}: ${c.level} ${c.ratio}`));
}
